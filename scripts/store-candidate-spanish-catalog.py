source = PLUGIN.read_text(encoding="utf-8")
pattern = re.compile(r"(?:__|_e|esc_html__|esc_html_e|esc_attr__|esc_attr_e)\(\s*'((?:\\'|[^'])*)'\s*,\s*'gestion-resenas'\s*\)")
msgids = sorted({match.replace("\\'", "'") for match in pattern.findall(source)})
missing = [msgid for msgid in msgids if msgid not in es]
if missing:
    print("Missing Spanish translations:")
    for msgid in missing:
        print(f" - {msgid}")
    sys.exit(1)


def q(value: str) -> str:
    return value.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')

